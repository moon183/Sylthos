    index=dict(schema_version=1,categories=groups,scenes=[])
    for identity,category,name,role,profile,criteria,emphasis,source_key in SCENES:
        focuses=[dict(dimension=dimension,label=label,evidence=evidence,question=question)
                 for dimension,(label,evidence,question) in zip(('method','evidence','limits'),criteria)]
        sources=[] if source_key is None else [dict(title=SOURCES[source_key][0],url=SOURCES[source_key][1])]
